"""Spatially correlated Gaussian random fields (spectral / FFT method).

A field with power spectrum ``P(k)`` is generated by filtering white noise in the wavenumber
domain and normalised to zero mean and unit variance. Anisotropy enters through the scaled
wavenumber ``k_a**2 = (k_along * a_along)**2 + (k_across * a_across)**2 + (k_z * a_z)**2``,
where *along* is the horizontal direction ``strike_deg`` (clockwise from north) and
*across* is perpendicular to it. Spectra (Sato & Fehler, *Seismic Wave Propagation and
Scattering in the Heterogeneous Earth*, ch. 2), in ``d`` dimensions:

- ``von_karman``: ``(1 + k_a**2) ** -(hurst + d/2)``; ``hurst`` sets roughness (small = rough,
  self-similar over scales shorter than the correlation length),
- ``exponential``: von Kármán with ``hurst = 0.5``,
- ``gaussian``: ``exp(-k_a**2 / 4)``; very smooth.

Each axis is padded (default twice that axis's correlation length per side; the larger
horizontal length for both horizontal axes, since strike can rotate them) before the FFT so the
periodic wrap-around of the spectral method does not correlate opposite edges. FFTs use all
CPU cores (``scipy.fft``).
"""

from __future__ import annotations

import math
import os
from typing import Literal

import numpy as np
import numpy.typing as npt
import scipy.fft
from pydantic import BaseModel, ConfigDict, Field

__all__ = ["CorrelationSpec", "correlated_field"]

FloatArray = npt.NDArray[np.float64]


class CorrelationSpec(BaseModel):
    """Spatial correlation of a heterogeneity field."""

    model_config = ConfigDict(extra="forbid")

    correlation: Literal["von_karman", "exponential", "gaussian"] = "von_karman"
    hurst: float = Field(0.3, gt=0, le=1, description="von_karman roughness exponent")
    corr_len_km: tuple[float, float, float] = Field(
        (2.0, 2.0, 0.5), description="along strike, across strike, vertical (km)"
    )
    strike_deg: float = Field(0.0, description="along-strike azimuth, degrees clockwise from N")

    def exponent(self) -> float | None:
        """von Kármán Hurst exponent, or ``None`` for Gaussian."""
        if self.correlation == "gaussian":
            return None
        return 0.5 if self.correlation == "exponential" else self.hurst


def correlated_field(
    shape: tuple[int, ...],
    spacing_km: float,
    spec: CorrelationSpec,
    rng: np.random.Generator,
    pad_km: float | None = None,
) -> FloatArray:
    """Zero-mean, unit-variance correlated field on a regular grid.

    Parameters
    ----------
    shape : tuple of int
        ``(nx, ny, nz)`` for a volume or ``(nx, ny)`` for a horizontal surface; x is east,
        y north, z down.
    spacing_km : float
        Grid spacing (same in every direction).
    spec : CorrelationSpec
        Correlation model; for 2D fields only the horizontal lengths are used.
    rng : numpy.random.Generator
        Source of the white noise.
    pad_km : float, optional
        Padding added to each side of every axis before the FFT; default twice the axis's
        correlation length.
    """
    d = len(shape)
    lengths = spec.corr_len_km[:d] if d == 3 else spec.corr_len_km[:2]
    horizontal = max(lengths[0], lengths[1])
    axis_len = [horizontal, horizontal] + ([lengths[2]] if d == 3 else [])
    npad = [math.ceil((2 * a if pad_km is None else pad_km) / spacing_km) for a in axis_len]
    full = tuple(n + 2 * p for n, p in zip(shape, npad, strict=True))

    k = [2 * np.pi * np.fft.fftfreq(n, spacing_km) for n in full[:-1]]
    k.append(2 * np.pi * np.fft.rfftfreq(full[-1], spacing_km))
    grids = np.meshgrid(*k, indexing="ij", sparse=True)
    theta = math.radians(spec.strike_deg)
    kx, ky = grids[0], grids[1]
    k_along = kx * math.sin(theta) + ky * math.cos(theta)
    k_across = kx * math.cos(theta) - ky * math.sin(theta)
    ka2 = (k_along * lengths[0]) ** 2 + (k_across * lengths[1]) ** 2
    if d == 3:
        ka2 = ka2 + (grids[2] * lengths[2]) ** 2

    hurst = spec.exponent()
    # Amplitude = sqrt(PSD): Gaussian exp(-k^2 a^2 / 4), von Karman (1 + k^2 a^2)^-(H + d/2).
    amplitude = np.exp(-ka2 / 8.0) if hurst is None else (1.0 + ka2) ** (-(hurst + d / 2) / 2)

    noise = rng.standard_normal(full)
    axes = tuple(range(d))
    workers = os.cpu_count() or 1
    spectrum = scipy.fft.rfftn(noise, axes=axes, workers=workers) * amplitude
    field = scipy.fft.irfftn(spectrum, s=full, axes=axes, workers=workers)
    inner = tuple(slice(p, p + n) for n, p in zip(shape, npad, strict=True))
    out: FloatArray = field[inner]
    out = out - out.mean()
    std = out.std()
    return out / std if std > 0 else out
